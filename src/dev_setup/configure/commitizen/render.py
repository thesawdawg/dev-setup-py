def sample_message(cfg: CommitizenConfig, *, breaking: bool = False) -> str:
    """The commit message `cz commit` would produce, rendered by hand from the same
    template that goes into the file — no Jinja2 dependency for a two-field sample."""
    selected = cfg.selected()
    key = selected[0].key if selected else "feat"
    scope = "(search)" if cfg.ask_scope else ""
    bang = "!" if breaking else ""
    out = f"{key}{scope}{bang}: add rate limiting"
    if cfg.ask_body:
        out += "\n\nrequests over 100/min now get a 429 instead of timing out"
    if cfg.ask_footer and breaking:
        out += f"\n\n{BREAKING_KEYWORD}: clients must handle 429"
    return out


def bump_rows(cfg: CommitizenConfig) -> list[tuple[str, str, str]]:
    """(type, increment, resulting version) for every selected type, plus the two
    breaking-change forms. What the review screen prints, and what the live `cz`
    check is compared against."""
    rows: list[tuple[str, str, str]] = []
    for change_type in cfg.selected():
        level = change_type.bump
        rows.append((f"{change_type.key}: …", level or "—", SAMPLE_BUMPS[level]))
    breaking = MINOR if cfg.major_version_zero else MAJOR
    rows.append((f"{_first_key(cfg)}!: …", breaking, SAMPLE_BUMPS[breaking]))
    rows.append((f"{BREAKING_KEYWORD}: … (footer)", breaking, SAMPLE_BUMPS[breaking]))
    return rows


def changelog_rows(cfg: CommitizenConfig) -> list[tuple[str, list[str]]]:
    """(changelog heading, what is filed under it) in emitted order.

    The breaking-change heading only collects commits carrying a `BREAKING CHANGE:`
    *footer* — checked against the binary. A `feat!:` still bumps the major, but it
    is written up under Features, because that is the type it declared.
    """
    grouped: dict[str, list[str]] = {section: [] for section in change_type_order(cfg)}
    for change_type in cfg.changelog_types():
        grouped[change_type.section].append(change_type.key)
    grouped[BREAKING_SECTION] = [f"commits with a {BREAKING_KEYWORD}: footer"]
    return list(grouped.items())


def _first_key(cfg: CommitizenConfig) -> str:
    selected = cfg.selected()
    return selected[0].key if selected else "feat"


def summary(cfg: CommitizenConfig) -> list[tuple[str, str]]:
    """(label, value) pairs for the review screen."""
    types = cfg.selected()
    bumping = [t.key for t in types if t.bump != NONE]
    return [
        ("Convention", cfg.convention_spec.label),
        ("Commit types", f"{len(types)} — {', '.join(t.key for t in types)}"),
        ("Bumping types", ", ".join(bumping) if bumping else "none"),
        ("Changelog sections", ", ".join(s for s, _ in changelog_rows(cfg))),
        ("Version from", cfg.provider_spec.label),
        ("Version scheme", cfg.version_scheme),
        ("Tag format", cfg.tag_format.replace("$version", SAMPLE_VERSION)),
        ("Changelog on bump", "yes" if cfg.update_changelog_on_bump else "no"),
        ("0.x mode", "yes — breaking changes bump the minor" if cfg.major_version_zero else "no"),
        ("Writes to", cfg.target),
    ]


def unchangelogged(cfg: CommitizenConfig) -> list[ChangeType]:
    return [t for t in cfg.selected() if not t.changelog]
