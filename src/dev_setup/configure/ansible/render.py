def summary(cfg: AnsibleConfig) -> list[tuple[str, str]]:
    rendered = data(cfg)
    rows = [
        ("starting point", cfg.preset),
        ("sections", ", ".join(rendered) or "none"),
        ("settings", str(sum(len(body) for body in rendered.values()))),
        ("writes to", str(cfg.target)),
    ]
    if cfg.extra:
        rows.append(("carried over", ", ".join(sorted(cfg.extra))))
    return rows


def setting_rows(cfg: AnsibleConfig) -> list[tuple[str, str, str, str]]:
    """(section, key, value, why it matters)."""
    rows: list[tuple[str, str, str, str]] = []
    for setting in cfg.changed().values():
        rows.append((
            setting.section,
            setting.ini_key,
            _value(setting, getattr(cfg, setting.key)),
            setting.why or setting.description,
        ))
    for section, body in cfg.extra.items():
        for key, value in body.items():
            rows.append((section, key, value, "carried over — not set by this wizard"))
    return rows


def diff(old: str, new: str) -> list[str]:
    import difflib

    return list(
        difflib.unified_diff(
            old.splitlines(), new.splitlines(), fromfile="current", tofile="new", lineterm=""
        )
    )


