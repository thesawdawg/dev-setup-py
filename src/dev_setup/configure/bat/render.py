def summary(cfg: BatConfig) -> list[tuple[str, str]]:
    if cfg.uses_auto_theme():
        theme = "auto"
        if cfg.theme_dark or cfg.theme_light:
            theme += f" — {cfg.theme_dark or 'default'} / {cfg.theme_light or 'default'}"
    else:
        theme = cfg.theme
    return [
        ("starting point", cfg.preset),
        ("theme", theme),
        ("decorations", ", ".join(cfg.components) if cfg.components else "none (plain)"),
        ("paging", cfg.paging + (f" via {cfg.pager}" if cfg.pager else "")),
        ("writes to", str(cfg.target)),
    ]


def flag_rows(cfg: BatConfig) -> list[tuple[str, str, str]]:
    """(flag, value, what it does) for the review table."""
    by_flag = {setting.flag: setting for setting in SETTINGS.values()}
    rows = []
    for flag, value in flags(cfg):
        setting = by_flag.get(flag)
        rows.append((flag, value, setting.description if setting else ""))
    if not rows:
        rows.append(("(nothing)", "", "every bat default applies"))
    return rows


def shell_block(cfg: BatConfig) -> str:
    """The ~/.bashrc block. Never contains a blank line.

    `base.remove_bashrc_block` ends its block at the first blank line, so a blank
    line here would orphan everything after it when the block is removed.
    """
    from dev_setup.configure.bat.model import SHELL_BITS

    return "\n".join(SHELL_BITS[key].line for key in cfg.shell_bits if key in SHELL_BITS)


def diff(old: str, new: str) -> list[str]:
    import difflib

    return list(
        difflib.unified_diff(
            old.splitlines(), new.splitlines(), fromfile="current", tofile="new", lineterm=""
        )
    )


