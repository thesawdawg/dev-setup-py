"""Turn a `BtopConfig` into `btop.conf` text — by splicing, never rewriting.

btop's own deal with the config file is binary: it rewrites the *whole* file —
every key and its own comments, dropping anything else — or it leaves it
byte-identical. The rewrite happens when the first line is not this version's
`#?` header, when a value was rejected on load, or when a setting changed in-app
(`save_config_on_exit = true`; 1.3.0 always saves). So this module never
reconstructs the file: it replaces the value inside the existing line of each
modelled key and appends only keys that are absent *and* differ from the
effective default, leaving every other byte — comments, unknown keys, btop's own
comment blocks — untouched.

That is also why there is no "generated by devstuff" marker: the first btop
upgrade or in-app change rewrites the file and removes it, so the overwrite
prompt shows a diff instead.
"""

from __future__ import annotations

import difflib
import re
from dataclasses import dataclass

from dev_setup.configure.btop.model import SETTINGS, BtopConfig, Setting

_KEY = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*")
_INT = re.compile(r"-?\d+")
_ANSI = re.compile(r"\x1b\[[0-9;?]*[A-Za-z]")


@dataclass(frozen=True)
class Line:
    """One original line. `key` is set when the line is `key = value`; `raw_value`
    is the verbatim value text (quotes included, comment excluded) and `span` its
    slice into `raw` so a replacement can keep everything else byte-identical."""

    raw: str
    key: str | None = None
    raw_value: str = ""
    value: object = None
    span: tuple[int, int] = (0, 0)


def parse_value(raw: str) -> object:
    """Classify a verbatim value the way btop reads it: `"s"` (ends at the second
    quote — `"a"b"` is `a`), `true`/`false` case-insensitively, an integer, or a
    bare word as a string."""
    text = raw.strip()
    if text.startswith('"'):
        end = text.find('"', 1)
        return text[1:end] if end != -1 else text[1:]
    low = text.lower()
    if low == "true":
        return True
    if low == "false":
        return False
    if _INT.fullmatch(text):
        return int(text)
    return text


def parse(text: str) -> list[Line]:
    """Read a config file keeping every original line; comments and blank lines
    come through verbatim with `key` unset."""
    out: list[Line] = []
    for raw in text.splitlines():
        m = _KEY.match(raw)
        if not m:
            out.append(Line(raw=raw))
            continue
        start = m.end()
        rest = raw[start:]
        if rest.startswith('"'):
            end = rest.find('"', 1)
            stop = start + (end + 1 if end != -1 else len(rest))
        else:
            cut = re.search(r"\s#", rest)
            stop = start + (len(rest[: cut.start()].rstrip()) if cut else len(rest))
        raw_value = raw[start:stop]
        out.append(Line(
            raw=raw, key=m.group(1), raw_value=raw_value,
            value=parse_value(raw_value), span=(start, stop),
        ))
    return out


def values(text: str) -> dict[str, object]:
    """{key: parsed value} for the setting lines — the first occurrence wins, the
    same one the splice edits."""
    out: dict[str, object] = {}
    for line in parse(text):
        if line.key is not None:
            out.setdefault(line.key, line.value)
    return out


def encode(setting: Setting, value: object) -> str:
    """bool -> `true`/`false`, int -> digits, everything else -> `"value"`."""
    if setting.kind == "bool":
        return "true" if value else "false"
    if setting.kind == "int":
        return str(int(value))
    return f'"{value}"'


def _fits(setting: Setting, value: object) -> bool:
    """Whether a parsed value could hold `setting`'s kind."""
    if setting.kind == "bool":
        return isinstance(value, bool)
    if setting.kind == "int":
        return isinstance(value, int) and not isinstance(value, bool)
    return isinstance(value, str)


def effective_default(setting: Setting, found) -> object:
    """What this binary would fall back to: the parsed value from its own
    defaults text when it has one for the key, else the modelled default."""
    raw = found.defaults.get(setting.key)
    if raw is not None:
        parsed = parse_value(raw)
        if _fits(setting, parsed):
            return parsed
    return setting.default


def known_keys(found) -> set[str]:
    """The modelled keys this binary accepts. `found.keys` None means btop could
    not be asked — then every modelled key counts as known."""
    if found.keys is None:
        return set(SETTINGS)
    return set(SETTINGS) & set(found.keys)


def _new_base(found) -> str:
    """A fresh file: this binary's own header line verbatim when known (never
    constructed — `#? Config file for btop v.1.4.6` vs `v. 1.3.0` differ), then a
    note about the rewrite-on-save behaviour."""
    lines: list[str] = []
    if found.header:
        lines += [found.header, ""]
    lines += [
        "# Written by `devstuff configure btop`. btop rewrites this file — every",
        "# setting and its own comments — whenever it saves, and that is expected.",
        "",
    ]
    return "\n".join(lines)


def to_text(cfg: BtopConfig, found) -> str:
    """The file as it will be written: the existing file's text spliced in place,
    or a minimal new file when the target does not exist."""
    try:
        base = cfg.target.read_text(encoding="utf-8", errors="replace")
    except OSError:
        base = _new_base(found)

    known = known_keys(found)
    out: list[str] = []
    seen: set[str] = set()
    for line in parse(base):
        if line.key in known and line.key not in seen:
            seen.add(line.key)
            want = getattr(cfg, line.key)
            if line.value != want:
                start, stop = line.span
                out.append(
                    line.raw[:start] + encode(SETTINGS[line.key], want) + line.raw[stop:]
                )
                continue
        out.append(line.raw)

    for key, setting in SETTINGS.items():
        if key in seen or key not in known:
            continue
        want = getattr(cfg, key)
        if want != effective_default(setting, found):
            out.append(f"{key} = {encode(setting, want)}")
    return "\n".join(out) + "\n"


def matches(text: str, cfg: BtopConfig, found) -> bool:
    """Whether the written file says what `cfg` says, for every key this binary
    knows — the splice verifies itself the same way commitizen's pyproject
    splice does."""
    on_disk = values(text)
    for key in known_keys(found):
        setting = SETTINGS[key]
        want = getattr(cfg, key)
        if key in on_disk:
            if on_disk[key] != want:
                return False
        elif want != effective_default(setting, found):
            return False
    return True


def _display(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def summary(cfg: BtopConfig, found) -> list[tuple[str, str]]:
    """Rows for the review screen: theme and boxes always, then only the settings
    that differ from the effective default."""
    rows = [("preset", cfg.preset)]
    for key, setting in SETTINGS.items():
        value = getattr(cfg, key)
        if key in ("color_theme", "shown_boxes") or value != effective_default(
            setting, found
        ):
            rows.append((setting.label, _display(value)))
    return rows


def diff(old: str, new: str) -> list[str]:
    return list(
        difflib.unified_diff(
            old.splitlines(), new.splitlines(), fromfile="current", tofile="new",
            lineterm="",
        )
    )


def strip_ansi(text: str) -> str:
    return _ANSI.sub("", text)


