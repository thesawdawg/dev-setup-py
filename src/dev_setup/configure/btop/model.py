# `save_config_on_exit` changes how btop itself treats the file — a preset must
# never decide it; only the user's explicit answer may. Pinned by a test.
_NEVER_IN_A_PRESET = {"save_config_on_exit"}


# ---------------------------------------------------------------------------
# The config
# ---------------------------------------------------------------------------


@dataclass
class BtopConfig:
    preset: str = DEFAULT_PRESET

    color_theme: str = "Default"
    theme_background: bool = True
    truecolor: bool = True
    rounded_corners: bool = True
    graph_symbol: str = "braille"

    shown_boxes: str = "cpu mem net proc"
    proc_left: bool = False
    cpu_bottom: bool = False
    mem_below_net: bool = False

    update_ms: int = 2000
    vim_keys: bool = False
    disable_mouse: bool = False
    clock_format: str = "%X"
    background_update: bool = True
    save_config_on_exit: bool = True

    proc_sorting: str = "cpu lazy"
    proc_tree: bool = False
    proc_per_core: bool = False
    proc_mem_bytes: bool = True
    proc_cpu_graphs: bool = True
    proc_filter_kernel: bool = False

    temp_scale: str = "celsius"
    base_10_sizes: bool = False

    target: Path = DEFAULT_CONFIG_PATH

    def boxes(self) -> list[str]:
        return self.shown_boxes.split()


