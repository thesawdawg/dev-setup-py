"""The data behind the btop wizard. Everything else in the package reads this.

`SETTINGS` is ordered — declaration order is prompt order. `BtopConfig` carries one
field per setting, and each field's default *is* `Setting.default`; a test pins
that pairing so a drift can't silently freeze the wrong value into a file.

Measured against btop 1.3.0 (Ubuntu 24.04 apt), 1.4.6 (Ubuntu 26.04 apt, GPU build)
and 1.4.7 (upstream static musl) — the record is docs/specs/btop-config/:

- **btop rewrites the whole file, or leaves it alone.** It rewrites — every key and
  its own comments, dropping anything else — when the first line is not this
  version's `#?` header, when a value was rejected on load, or when a setting was
  changed in-app (with `save_config_on_exit = true`; 1.3.0 has no such key and
  always saves). Otherwise the file is left byte-identical — comments, unknown keys
  and partial files included. So `render.to_text` *splices* into the existing file
  rather than rewriting it, and a "generated by devstuff" marker could not be
  trusted anyway.
- **Validation is asymmetric, in three classes.** Some bad values are rejected and
  logged (`update_ms = "abc"`, `vim_keys = yes`, `graph_symbol = "bad"`); some are
  rejected silently (`shown_boxes` with an unknown token); some are *kept* silently
  (`proc_sorting = "Memory"`, `temp_scale = "bogus"`, an unknown `color_theme`).
  `validate.verify` and `validate.launch` exist because btop will not say which.
- **The key set depends on version AND build flags.** 1.4.7 adds `disable_mouse`,
  `disable_presets`, `proc_follow_detailed`, `swap_upload_download`; the 1.4.6 GPU
  build adds `shown_gpus`, `graph_symbol_gpu`, `custom_gpu_name0..5` and friends;
  1.3.0 lacks `save_config_on_exit`, `disable_mouse` and `base_10_bitrate`.
  `detect` reads the real key set from `btop --default-config` (or a first-run
  probe on 1.3.0, which lacks the flag) and the wizard only asks about keys this
  binary knows — and never writes one it does not.
- **A `"` can never appear inside a string value** — `clock_format = "a"b"` is
  saved back as `"a"`, because a quoted value ends at the second quote.

Enum `choices` are the values btop's own `--default-config` comments list, not a
recalled set.
"""

