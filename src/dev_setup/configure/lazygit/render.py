def summary(cfg: LazygitConfig) -> list[tuple[str, str]]:
    rows = [
        ("starting point", cfg.preset),
        ("settings", str(len(cfg.changed()))),
        ("icons", cfg.nerd_fonts_version and f"Nerd Font v{cfg.nerd_fonts_version}" or "off"),
        ("diff pager", cfg.pager or "git's own"),
        ("writes to", str(cfg.target)),
    ]
    if cfg.extra:
        rows.append(("carried over", ", ".join(sorted(cfg.extra))))
    return rows


def setting_rows(cfg: LazygitConfig) -> list[tuple[str, str, str, str]]:
    """(group, path, value, note)."""
    from dev_setup.configure.lazygit.model import GROUPS

    rows = []
    for key, setting in cfg.changed().items():
        value = getattr(cfg, key)
        rows.append((
            GROUPS[setting.group].label,
            setting.path,
            _scalar(value),
            setting.why or setting.description,
        ))
    for key in cfg.extra:
        rows.append(("Carried over", key, "…", "not set by this wizard"))
    return rows


def diff(old: str, new: str) -> list[str]:
    import difflib

    return list(
        difflib.unified_diff(
            old.splitlines(), new.splitlines(), fromfile="current", tofile="new", lineterm=""
        )
    )


